#!/usr/bin/env python3
"""Build part_d.json for 2022-12 N2 listening (問題1-5)."""
import json

AUDIO = "/static/audio/2022-12-N2-listening.mp3"

groups = []
questions = []
explanations = []
vocabulary = []

def add_group(local_id, title, content, sort_order):
    groups.append({
        "local_id": local_id,
        "section_code": "listening",
        "group_type": "dialogue",
        "title": title,
        "content": content,
        "sort_order": sort_order,
    })

def add_q(mondai_no, nis, stem, options, correct, group_local_id):
    questions.append({
        "section_code": "listening",
        "mondai_no": mondai_no,
        "number_in_section": nis,
        "stem": stem,
        "options": [{"key": str(i+1), "text": t} for i, t in enumerate(options)],
        "correct_option": str(correct),
        "group_local_id": group_local_id,
        "audio_url": AUDIO,
    })

def add_e(nis, key_point, analysis_zh, distractors, option_readings, option_meanings):
    explanations.append({
        "number_in_section": nis,
        "key_point": key_point,
        "analysis_zh": analysis_zh,
        "distractors": distractors,
        "option_readings": option_readings,
        "option_meanings": option_meanings,
    })

def add_v(nis, word, reading, meaning_zh, etymology_en=None):
    v = {"number_in_section": nis, "word": word, "reading": reading, "meaning_zh": meaning_zh}
    if etymology_en:
        v["etymology_en"] = etymology_en
    vocabulary.append(v)

