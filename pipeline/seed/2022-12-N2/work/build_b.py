G = "g_text9"
questions = []
explanations = []
vocabulary = []

def add_q(n, mondai, qtype, stem, opts, correct, group=None, target=None):
    questions.append({
        "section_code": "lang_reading",
        "qtype_code": qtype,
        "mondai_no": mondai,
        "number_in_section": n,
        "stem": stem,
        "options": [{"key": str(i+1), "text": o} for i, o in enumerate(opts)],
        "correct_option": str(correct),
        "group_local_id": group,
        "target_text": target,
        "audio_url": None,
    })

def add_e(n, key_point, analysis, distractors, readings=None, meanings=None, evidence=None):
    explanations.append({
        "section_code": "lang_reading",
        "number_in_section": n,
        "key_point": key_point,
        "analysis_zh": analysis,
        "distractors": [{"option": str(o), "why_wrong": w} for o, w in distractors],
        "evidence": evidence,
        "option_readings": readings or {},
        "option_meanings": meanings or {},
    })

def add_v(n, word, reading, meaning, pos=None, ex=None):
    vocabulary.append({
        "section_code": "lang_reading",
        "number_in_section": n,
        "word": word, "reading": reading, "pos": pos,
        "meaning_zh": meaning, "example_sentence": ex,
    })

