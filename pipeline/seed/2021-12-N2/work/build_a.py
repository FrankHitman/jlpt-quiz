def q(mondai, n, qtype, stem, opts, correct, target=None):
    return {
        "group_local_id": None, "section_code": "lang_reading", "qtype_code": qtype,
        "mondai_no": mondai, "number_in_section": n, "stem": stem,
        "options": [{"key": str(i+1), "text": t} for i, t in enumerate(opts)],
        "correct_option": str(correct), "target_text": target,
    }

def e(n, key_point, analysis, distractors, readings=None, meanings=None):
    return {
        "section_code": "lang_reading", "number_in_section": n, "key_point": key_point,
        "analysis_zh": analysis, "evidence": None,
        "distractors": [{"option": str(o), "why_wrong": w} for o, w in distractors],
        "option_readings": readings or {}, "option_meanings": meanings or {},
    }

def v(n, word, reading, meaning, pos=None, ex=None, note=None, etym=None):
    return {
        "section_code": "lang_reading", "number_in_section": n, "word": word,
        "reading": reading, "pos": pos, "meaning_zh": meaning,
        "example_sentence": ex, "note": note, "etymology_en": etym,
    }

