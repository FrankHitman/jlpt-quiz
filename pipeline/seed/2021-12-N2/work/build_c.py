import json

groups = []
questions = []
explanations = []
vocabulary = []

def add_group(local_id, title, content, sort_order):
    groups.append({
        "local_id": local_id,
        "section_code": "lang_reading",
        "group_type": "passage",
        "title": title,
        "content": content,
        "sort_order": sort_order,
    })

def add_q(mondai_no, nis, qtype, group_local_id, stem, options, correct):
    questions.append({
        "group_local_id": group_local_id,
        "section_code": "lang_reading",
        "qtype_code": qtype,
        "mondai_no": mondai_no,
        "number_in_section": nis,
        "stem": stem,
        "options": [{"key": str(i+1), "text": o} for i, o in enumerate(options)],
        "correct_option": str(correct),
        "target_text": None,
        "audio_url": None,
    })

def add_e(nis, key_point, analysis_zh, distractors, evidence, readings, meanings):
    explanations.append({
        "section_code": "lang_reading",
        "number_in_section": nis,
        "key_point": key_point,
        "analysis_zh": analysis_zh,
        "distractors": [{"option": str(k), "why_wrong": v} for k, v in distractors],
        "evidence": evidence,
        "option_readings": readings,
        "option_meanings": meanings,
    })

def add_v(nis, word, reading, pos, meaning_zh, example=None, note=None, etymology=None):
    vocabulary.append({
        "section_code": "lang_reading",
        "number_in_section": nis,
        "word": word,
        "reading": reading,
        "pos": pos,
        "meaning_zh": meaning_zh,
        "example_sentence": example,
        "note": note,
        "etymology_en": etymology,
    })

