groups, questions, explanations, vocabulary = [], [], [], []

def add_group(local_id, title, content, sort):
    groups.append({"local_id": local_id, "section_code": "listening",
                   "group_type": "dialogue", "title": title, "content": content,
                   "sort_order": sort})

def add_q(mondai, nis, qtype, stem, options, correct, glid, title):
    questions.append({"section_code": "listening", "qtype_code": qtype,
        "mondai_no": mondai, "number_in_section": nis, "stem": stem,
        "options": [{"key": str(i+1), "text": t} for i, t in enumerate(options)],
        "correct_option": str(correct), "target_text": None,
        "group_local_id": glid, "audio_url": AUDIO})

def add_e(nis, key_point, analysis, distractors, readings=None, meanings=None, evidence=None):
    explanations.append({"section_code": "listening", "number_in_section": nis,
        "key_point": key_point, "analysis_zh": analysis,
        "distractors": [{"option": str(o), "why_wrong": w} for o, w in distractors],
        "evidence": evidence, "option_readings": readings or {},
        "option_meanings": meanings or {}})

def add_v(nis, word, reading, pos, meaning, example=None, note=None, ety=None):
    vocabulary.append({"section_code": "listening", "number_in_section": nis,
        "word": word, "reading": reading, "pos": pos, "meaning_zh": meaning,
        "example_sentence": example, "note": note, "etymology_en": ety})

