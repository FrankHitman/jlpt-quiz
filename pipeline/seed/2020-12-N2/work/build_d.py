AUDIO = "/static/audio/2020-12-N2-listening.mp3"
groups, questions, explanations, vocabulary = [], [], [], []

def G(local_id, title, content, sort_order):
    groups.append({"local_id": local_id, "section_code": "listening",
                   "group_type": "dialogue", "title": title, "content": content,
                   "sort_order": sort_order})

def Q(nis, mondai, qtype, stem, options, correct):
    if mondai == 5:
        gn = 1 if nis == 28 else 2
    else:
        gn = nis - {1: 0, 2: 5, 3: 11, 4: 16}[mondai]
    questions.append({"group_local_id": f"g_lis{mondai}_{gn}",
                      "section_code": "listening", "qtype_code": qtype,
                      "mondai_no": mondai, "number_in_section": nis,
                      "stem": stem, "options": options,
                      "correct_option": correct, "audio_url": AUDIO,
                      "target_text": None})

def E(nis, key_point, analysis_zh, distractors, option_readings, option_meanings):
    explanations.append({"section_code": "listening", "number_in_section": nis,
                         "key_point": key_point, "analysis_zh": analysis_zh,
                         "distractors": distractors, "evidence": None,
                         "option_readings": option_readings,
                         "option_meanings": option_meanings})

def V(nis, word, reading, pos, meaning_zh, example_sentence=None, note=None, etymology_en=None):
    vocabulary.append({"section_code": "listening", "number_in_section": nis,
                       "word": word, "reading": reading, "pos": pos,
                       "meaning_zh": meaning_zh, "example_sentence": example_sentence,
                       "note": note, "etymology_en": etymology_en})

def OPT(*pairs):
    return [{"key": str(i+1), "text": t} for i, t in enumerate(pairs)]

