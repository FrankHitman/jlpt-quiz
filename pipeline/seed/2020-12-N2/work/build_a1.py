"""2020-12 N2 問題1–2 (Q1–10) 轉錄數據"""
import json

questions = []
explanations = []
vocabulary = []

def Q(nis, mondai, qtype, stem, options, correct, target=None):
    questions.append({
        "group_local_id": None,
        "section_code": "lang_reading",
        "qtype_code": qtype,
        "mondai_no": mondai,
        "number_in_section": nis,
        "stem": stem,
        "options": [{"key": str(i+1), "text": t} for i, t in enumerate(options)],
        "correct_option": str(correct),
        "target_text": target,
        "audio_url": None,
    })

def E(nis, key_point, analysis_zh, distractors, option_readings=None, option_meanings=None):
    explanations.append({
        "section_code": "lang_reading",
        "number_in_section": nis,
        "key_point": key_point,
        "analysis_zh": analysis_zh,
        "distractors": [{"option": str(o), "why_wrong": w} for o, w in distractors],
        "evidence": None,
        "option_readings": option_readings or {},
        "option_meanings": option_meanings or {},
    })

def V(nis, word, reading, pos, meaning_zh, example_sentence=None, note=None, etymology_en=None):
    vocabulary.append({
        "section_code": "lang_reading",
        "number_in_section": nis,
        "word": word,
        "reading": reading,
        "pos": pos,
        "meaning_zh": meaning_zh,
        "example_sentence": example_sentence,
        "note": note,
        "etymology_en": etymology_en,
    })

