"""Build part_a.json for 2021-07 N2 (Q1-30, vocab section)."""
import json

SC = "lang_reading"
questions, explanations, vocabulary = [], [], []

def add_q(n, mondai, qtype, stem, opts, correct, target=None):
    questions.append({
        "group_local_id": None,
        "section_code": SC,
        "qtype_code": qtype,
        "mondai_no": mondai,
        "number_in_section": n,
        "stem": stem,
        "options": [{"key": str(i+1), "text": t} for i, t in enumerate(opts)],
        "correct_option": str(correct),
        "target_text": target,
    })

def add_e(n, key_point, analysis, distractors, readings=None, meanings=None):
    explanations.append({
        "section_code": SC,
        "number_in_section": n,
        "key_point": key_point,
        "analysis_zh": analysis,
        "distractors": [{"option": str(o), "why_wrong": w} for o, w in distractors],
        "evidence": None,
        "option_readings": readings or {},
        "option_meanings": meanings or {},
    })

def add_v(n, word, reading, meaning, pos=None, ex=None, note=None, etym=None):
    vocabulary.append({
        "section_code": SC,
        "number_in_section": n,
        "word": word,
        "reading": reading,
        "pos": pos,
        "meaning_zh": meaning,
        "example_sentence": ex,
        "note": note,
        "etymology_en": etym,
    })

