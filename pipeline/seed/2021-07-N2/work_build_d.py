groups, questions, explanations, vocabulary = [], [], [], []

def add_group(local_id, title, content, sort_order):
    groups.append({"local_id": local_id, "section_code": "listening",
                   "group_type": "dialogue", "title": title,
                   "content": content, "sort_order": sort_order})

def add_q(mondai_no, nis, qtype, stem, options, correct, group_local_id):
    questions.append({"group_local_id": group_local_id, "section_code": "listening",
                      "qtype_code": qtype, "mondai_no": mondai_no,
                      "number_in_section": nis, "stem": stem,
                      "options": [{"key": str(i+1), "text": t} for i, t in enumerate(options)],
                      "correct_option": str(correct), "target_text": None,
                      "audio_url": AUDIO})

def add_e(nis, key_point, analysis_zh, distractors, option_readings=None, option_meanings=None):
    explanations.append({"section_code": "listening", "number_in_section": nis,
                         "key_point": key_point, "analysis_zh": analysis_zh,
                         "distractors": distractors, "evidence": None,
                         "option_readings": option_readings or {},
                         "option_meanings": option_meanings or {}})

def add_v(nis, word, reading, pos, meaning_zh, example_sentence=None, note=None, etymology_en=None):
    vocabulary.append({"section_code": "listening", "number_in_section": nis,
                       "word": word, "reading": reading, "pos": pos,
                       "meaning_zh": meaning_zh, "example_sentence": example_sentence,
                       "note": note, "etymology_en": etymology_en})

def D(opt, why):
    return {"option": str(opt), "why_wrong": why}

so = 0
def next_so():
    global so
    so += 1
    return so

