import json

SEC = "lang_reading"

def q(nis, mondai, qtype, stem, opts, correct, group=None):
    return {
        "group_local_id": group,
        "section_code": SEC,
        "qtype_code": qtype,
        "mondai_no": mondai,
        "number_in_section": nis,
        "stem": stem,
        "options": [{"key": str(i+1), "text": t} for i, t in enumerate(opts)],
        "correct_option": str(correct),
        "target_text": None,
    }

def e(nis, key_point, analysis, distractors, readings, meanings):
    return {
        "section_code": SEC,
        "number_in_section": nis,
        "key_point": key_point,
        "analysis_zh": analysis,
        "distractors": [{"option": str(o), "why_wrong": w} for o, w in distractors],
        "evidence": None,
        "option_readings": readings,
        "option_meanings": meanings,
    }

def v(nis, word, reading, pos, meaning, ex=None, note=None, ety=None):
    return {
        "section_code": SEC, "number_in_section": nis, "word": word,
        "reading": reading, "pos": pos, "meaning_zh": meaning,
        "example_sentence": ex, "note": note, "etymology_en": ety,
    }

