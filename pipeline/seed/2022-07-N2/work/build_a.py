import json

Q = []  # questions
E = []  # explanations
V = []  # vocabulary

def add_q(nis, mondai, qtype, stem, options, correct, target=None):
    Q.append({
        "group_local_id": None,
        "section_code": "lang_reading",
        "qtype_code": qtype,
        "mondai_no": mondai,
        "number_in_section": nis,
        "stem": stem,
        "options": [{"key": str(i+1), "text": t} for i, t in enumerate(options)],
        "correct_option": str(correct),
        "target_text": target,
        "audio_url": None,
    })

def add_e(nis, key_point, analysis, distractors, readings, meanings):
    E.append({
        "section_code": "lang_reading",
        "number_in_section": nis,
        "key_point": key_point,
        "analysis_zh": analysis,
        "distractors": [{"option": str(o), "why_wrong": w} for o, w in distractors],
        "evidence": None,
        "option_readings": readings,
        "option_meanings": meanings,
    })

def add_v(nis, word, reading, pos, meaning, ex=None, note=None, etym=None):
    V.append({
        "section_code": "lang_reading",
        "number_in_section": nis,
        "word": word, "reading": reading, "pos": pos,
        "meaning_zh": meaning, "example_sentence": ex,
        "note": note, "etymology_en": etym,
    })

