OPT_RE = re.compile(r"^(\d)\.\s?(.*)$")


def parse_opts(s):
    # '1. a / 2. b / ...' 或每行一個選項 -> [{'key':'1','text':'a'},...]
    opts = []
    for chunk in s.replace("\r", "").split("\n"):
        for p in chunk.split(" / "):
            p = p.strip()
            m = OPT_RE.match(p)
            if m:
                opts.append({"key": m.group(1), "text": m.group(2).strip()})
    return opts


def parse_questions(text):
    """解析 'Qn:' 題干 + 選項，回傳 {n: {'stem':..., 'options':[...]}}。"""
    questions = {}
    lines = text.split("\n")
    i, n = 0, len(lines)
    cur = None

    def flush():
        if cur and cur["options"]:
            cur["stem"] = "\n".join(cur["stem_parts"]).strip()
            questions[cur["n"]] = {"stem": cur["stem"], "options": cur["options"]}

    while i < n:
        line = lines[i].rstrip()
        m = re.match(r"^Q(\d+):\s*(.*)$", line)
        if m:
            flush()
            qn, rest = int(m.group(1)), m.group(2).strip()
            cur = {"n": qn, "stem_parts": [], "options": []}
            if re.match(r"^1\.\s", rest):
                cur["options"] = parse_opts(rest)
                flush()
                cur = None
            elif rest:
                cur["stem_parts"].append(rest)
            i += 1
            continue
        if cur is not None:
            s = line.strip()
            if re.match(r"^1\.\s", s):
                buf = s
                while len(parse_opts(buf)) < 4 and i + 1 < n:
                    i += 1
                    nxt = lines[i].strip()
                    if nxt == "" or re.match(r"^(Q\d+:|#)", nxt):
                        break
                    buf += "\n" + nxt
                cur["options"] = parse_opts(buf)
                flush()
                cur = None
            elif s == "" or s.startswith("#") or s.startswith("[") or s.startswith("問題"):
                pass
            else:
                cur["stem_parts"].append(s)
        i += 1
    flush()
    return questions


def parse_passages(text, extra_markers=()):
    """依 [短文]/[文章] 標記切出文章段落（不含其後的題目）。"""
    passages = []
    lines = text.split("\n")
    i, n = 0, len(lines)
    while i < n:
        line = lines[i].strip()
        is_marker = (
            re.match(r"^\[短文", line)
            or re.match(r"^\[文章", line)
            or line in extra_markers
        )
        if is_marker:
            buf = []
            i += 1
            while i < n:
                s = lines[i].strip()
                if re.match(r"^Q\d+:", s) or re.match(r"^質問\d", s) or s.startswith("##"):
                    break
                buf.append(lines[i].rstrip())
                i += 1
            while buf and buf[0].strip() == "":
                buf.pop(0)
            while buf and buf[-1].strip() == "":
                buf.pop()
            passages.append("\n".join(buf))
            continue
        i += 1
    return passages


def parse_listening(text):
    """解析聽解選項，回傳 {number_in_section: {'options':[...]}}。"""
    result = {}
    offset = {1: 0, 2: 5, 3: 11, 4: 16, 5: 27}
    mondai = None
    ban = None
    lines = text.split("\n")
    i, n = 0, len(lines)
    while i < n:
        line = lines[i].strip()
        m = re.match(r"^###\s*聽解問題(\d)(?![・\d])", line)
        if m:
            mondai = int(m.group(1))
            ban = None
            i += 1
            continue
        m = re.match(r"^###\s*聽解問題\d・(\d+)番", line)
        if m:
            ban = int(m.group(1))
            i += 1
            continue
        m = re.match(r"^質問(\d)[：:]\s*(.*)$", line)
        if m:
            nis = 28 + int(m.group(1))  # 質問1→29, 質問2→30
            result[nis] = {"options": parse_opts(m.group(2).strip())}
            i += 1
            continue
        if re.match(r"^1\.\s", line) and mondai and ban:
            buf = line
            while len(parse_opts(buf)) < 4 and i + 1 < n:
                i += 1
                nxt = lines[i].strip()
                if nxt == "" or re.match(r"^(###|Q\d)", nxt):
                    break
                buf += "\n" + nxt
            result[offset[mondai] + ban] = {"options": parse_opts(buf)}
        i += 1
    return result


