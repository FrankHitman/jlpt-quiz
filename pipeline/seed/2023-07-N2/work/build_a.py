"""Build part_a.json for 2023-07 N2 (問題1-6, Q1-30)."""
import json

def Q(nis, mondai, qtype, stem, options, correct, target=None):
    return {
        "section_code": "lang_reading",
        "qtype_code": qtype,
        "mondai_no": mondai,
        "number_in_section": nis,
        "stem": stem,
        "options": [{"key": str(i + 1), "text": t} for i, t in enumerate(options)],
        "correct_option": str(correct),
        **({"target_text": target} if target else {}),
    }

def E(nis, key_point, analysis_zh, distractors, readings=None, meanings=None):
    return {
        "section_code": "lang_reading",
        "number_in_section": nis,
        "key_point": key_point,
        "analysis_zh": analysis_zh,
        "distractors": [{"option": str(o), "why_wrong": w} for o, w in distractors],
        "evidence": None,
        "option_readings": readings or {},
        "option_meanings": meanings or {},
    }

def V(nis, word, reading, meaning_zh, pos=None, example=None, etym=None):
    v = {"section_code": "lang_reading", "number_in_section": nis, "word": word,
         "reading": reading, "pos": pos, "meaning_zh": meaning_zh,
         "example_sentence": example}
    if etym:
        v["etymology_en"] = etym
    return v

