import json

AUDIO = "/static/audio/2023-07-N2-listening.mp3"
groups, questions, explanations, vocabulary = [], [], [], []
_sort = 0

def add_group(local_id, title, content):
    global _sort
    _sort += 1
    groups.append({"local_id": local_id, "section_code": "listening",
                   "group_type": "dialogue", "title": title,
                   "content": content, "sort_order": _sort})

def add_q(mondai, nis, stem, options, correct, group_local_id, qtype):
    questions.append({"group_local_id": group_local_id, "section_code": "listening",
                      "qtype_code": qtype, "mondai_no": mondai, "number_in_section": nis,
                      "stem": stem, "options": options, "correct_option": correct,
                      "target_text": None, "audio_url": AUDIO})

def add_e(nis, key_point, analysis_zh, distractors, readings=None, meanings=None):
    explanations.append({"section_code": "listening", "number_in_section": nis,
                         "key_point": key_point, "analysis_zh": analysis_zh,
                         "distractors": distractors, "evidence": None,
                         "option_readings": readings or {}, "option_meanings": meanings or {}})

def add_v(nis, word, reading, meaning_zh, pos=None, etymology_en=None):
    vocabulary.append({"section_code": "listening", "number_in_section": nis,
                       "word": word, "reading": reading, "pos": pos,
                       "meaning_zh": meaning_zh, "example_sentence": None,
                       "etymology_en": etymology_en})

