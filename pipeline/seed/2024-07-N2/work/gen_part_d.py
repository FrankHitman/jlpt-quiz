def has_kanji(s):
    return bool(re.search(r'[\u4e00-\u9fff]', s))

groups, questions, explanations, vocabulary = [], [], [], []

def add_group(local_id, title, content, sort_order):
    groups.append({"local_id": local_id, "section_code": "listening",
                   "group_type": "dialogue", "title": title,
                   "content": content, "sort_order": sort_order})

def add_q(group_local_id, qtype, mondai_no, nis, stem, options, correct):
    questions.append({"group_local_id": group_local_id, "section_code": "listening",
                      "qtype_code": qtype, "mondai_no": mondai_no,
                      "number_in_section": nis, "stem": stem, "options": options,
                      "correct_option": correct, "target_text": None})

def add_exp(nis, key_point, analysis_zh, distractors, readings, meanings):
    explanations.append({"section_code": "listening", "number_in_section": nis,
                         "key_point": key_point, "analysis_zh": analysis_zh,
                         "distractors": distractors, "evidence": None,
                         "option_readings": readings, "option_meanings": meanings})

def add_v(nis, word, reading, pos, meaning_zh, etymology_en=None):
    vocabulary.append({"section_code": "listening", "number_in_section": nis,
                       "word": word, "reading": reading, "pos": pos,
                       "meaning_zh": meaning_zh, "etymology_en": etymology_en,
                       "note": None, "example_sentence": None})

def opts4(texts):
    return [{"key": str(i+1), "text": t} for i, t in enumerate(texts)]

def rm(texts, readings, meanings):
    """只保留含漢字選項的注音/意思"""
    r = {k: v for k, v in readings.items() if has_kanji(dict(zip("1234", texts))[k])}
    m = {k: v for k, v in meanings.items() if has_kanji(dict(zip("1234", texts))[k])}
    return r, m

